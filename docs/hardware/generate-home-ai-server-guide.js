/** 页面内容区宽度（DXA），A4 左右页边距各约 720 */
const CONTENT_WIDTH = 9360;

/** 统一细边框，用于表格 */
const thinBorder = { style: BorderStyle.SINGLE, size: 4, color: "CCCCCC" };
const borders = { top: thinBorder, bottom: thinBorder, left: thinBorder, right: thinBorder };
const headerShading = { type: ShadingType.CLEAR, fill: "1F4E79" };
const altRowShading = { type: ShadingType.CLEAR, fill: "F2F7FB" };
const accentShading = { type: ShadingType.CLEAR, fill: "E8F0FE" };

/**
 * 创建普通段落
 * @param {string} text 段落文字
 * @param {object} [options] 字号、加粗、颜色等
 */
function p(text, options = {}) {
  return new Paragraph({
    spacing: { after: options.after ?? 120, before: options.before ?? 0, line: 276 },
    alignment: options.align,
    children: [
      new TextRun({
        text,
        font: "微软雅黑",
        size: options.size ?? 21,
        bold: options.bold,
        color: options.color ?? "222222",
        italics: options.italics,
      }),
    ],
  });
}

/**
 * 创建标题段落（使用内置 Heading 样式，便于生成目录）
 * @param {string} text 标题文字
 * @param {number} level HeadingLevel 枚举值
 */
function heading(text, level) {
  return new Paragraph({
    heading: level,
    spacing: { before: level === HeadingLevel.HEADING_1 ? 360 : 240, after: 160 },
    children: [new TextRun({ text, font: "微软雅黑", bold: true, color: "1F4E79" })],
  });
}

/**
 * 创建表格单元格
 * @param {string} text 单元格内容
 * @param {object} opts 宽度、是否表头、是否交替行、加粗等
 */
function cell(text, opts = {}) {
  const width = opts.width ?? 2000;
  return new TableCell({
    borders,
    width: { size: width, type: WidthType.DXA },
    shading: opts.header ? headerShading : opts.alt ? altRowShading : opts.accent ? accentShading : undefined,
    children: [
      new Paragraph({
        spacing: { before: 60, after: 60 },
        children: [
          new TextRun({
            text: String(text),
            font: "微软雅黑",
            size: opts.size ?? 18,
            bold: opts.header || opts.bold,
            color: opts.header ? "FFFFFF" : "222222",
          }),
        ],
      }),
    ],
  });
}

/**
 * 根据二维数组生成表格
 * @param {string[]} headers 表头
 * @param {string[][]} rows 数据行
 * @param {number[]} colWidths 各列宽度（DXA），总和应等于 CONTENT_WIDTH
 */
function makeTable(headers, rows, colWidths) {
  const headerRow = new TableRow({
    children: headers.map((h, i) => cell(h, { header: true, width: colWidths[i] })),
  });
  const dataRows = rows.map(
    (row, rowIndex) =>
      new TableRow({
        children: row.map((value, colIndex) =>
          cell(value, { width: colWidths[colIndex], alt: rowIndex % 2 === 1 })
        ),
      })
  );
  return new Table({
    width: { size: CONTENT_WIDTH, type: WidthType.DXA },
    columnWidths: colWidths,
    rows: [headerRow, ...dataRows],
  });
}

